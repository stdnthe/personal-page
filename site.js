const applyLanguage = (language) => {
  const dictionary = copy.en;
  document.documentElement.lang = "en";
  document.body.dataset.lang = "en";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-content]").forEach((node) => {
    const key = node.dataset.i18nContent;
    if (dictionary[key]) {
      node.setAttribute("content", dictionary[key]);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (dictionary[key]) {
      node.setAttribute("aria-label", dictionary[key]);
    }
  });

  if (document.body.dataset.titleKey && dictionary[document.body.dataset.titleKey]) {
    document.title = dictionary[document.body.dataset.titleKey];
  }

  try {
    localStorage.removeItem("preferred-language");
  } catch {
    document.body.dataset.preferredLanguage = "en";
  }
};

applyLanguage("en");
